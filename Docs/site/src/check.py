def explore(page):
    """The code explorer, used: type into the find box, switch trails and walk to a step, follow each kind of deep link."""
    errors = []
    root = page.query_selector("#explorer")
    if not root:
        return ["the explorer did not mount"]
    box = page.query_selector("#explorer textarea")
    box.click()
    box.evaluate("e => { e.__probe = 1; }")
    page.keyboard.type("Gate.observe", delay=25)
    page.wait_for_timeout(250)
    got = box.evaluate("""e => ({ same: e.isConnected && e.__probe === 1, focused: document.activeElement === e, end: e.selectionStart === e.value.length,
        first: (document.querySelector('#xp-results [role=option] b') || {}).textContent || '' })""")
    if not (got["same"] and got["focused"] and got["end"]):
        errors.append(f"typing into the find box lost it: {got}")
    if not got["first"].startswith("Gate.observe"):
        errors.append(f"finding Gate.observe listed {got['first']!r} first")
    page.keyboard.press("Enter")
    page.wait_for_timeout(150)
    if "Gate.observe" not in (root.get_attribute("data-scope") or ""):
        errors.append(f"Enter on the first match selected {root.get_attribute('data-scope')!r}")
    page.click('#explorer .xp-trails button[data-trail="inference"]')
    page.wait_for_timeout(150)
    if root.get_attribute("data-trail") != "inference":
        errors.append(f"the inference button left the walked trail at {root.get_attribute('data-trail')!r}")
    page.click('#explorer .xp-steps button[data-step="3"]')
    page.wait_for_timeout(150)
    want = page.evaluate("Braid.explorer.trailFile('inference', 3)")
    if root.get_attribute("data-file") != want or root.get_attribute("data-step") != "3" or root.get_attribute("data-trail") != "inference":
        errors.append(f"inference step 3 opened {root.get_attribute('data-file')}, not {want}")
    page.click('#explorer .xp-trails button[data-trail="qa-training"]')
    page.wait_for_timeout(150)
    want = page.evaluate("Braid.explorer.trailFile('qa-training', 1)")
    if root.get_attribute("data-trail") != "qa-training" or root.get_attribute("data-step") != "1" or root.get_attribute("data-file") != want:
        errors.append(f"the Q/A training button opened {root.get_attribute('data-trail')} step {root.get_attribute('data-step')} in {root.get_attribute('data-file')}, not step 1 in {want}")
    first = page.evaluate("(() => { const m = Braid.explorer.model(), sc = m.scopes[m.trails[0].steps[0].entries[0].scope]; return [sc.file.path, sc.tail, sc.sig, sc.id]; })()")
    for target, check in [("Sources/BraidCore/Mixture/Gate/Gate.swift:64", ("data-line", "64")), ("trail-training-6", ("data-step", "6")),
                          ("trail-inference-2;n=3", ("data-trail", "inference")), ("trail-qa-inference-4", ("data-trail", "qa-inference")), ("trail-4", ("data-step", "3")),
                          (first[0] + ":" + first[1], ("data-scope", first[3]))]:
        page.evaluate("t => { location.hash = t; }", target)
        page.wait_for_timeout(200)
        if root.get_attribute(check[0]) != check[1]:
            errors.append(f"#{target} left {check[0]} at {root.get_attribute(check[0])!r}, not {check[1]!r}")
    seen = page.evaluate("""() => { const p = document.querySelector('#explorer pre'), r = p.querySelector('.ln.sig');
        if (!r) return false; const a = p.getBoundingClientRect(), b = r.getBoundingClientRect(); return b.top >= a.top - 1 && b.bottom <= a.bottom + 1; }""")
    if not seen:
        errors.append("the selected declaration's signature line is not inside the source pane's view")
    return errors


def browse(paths, problems, shots, modes):
    from playwright.sync_api import sync_playwright
    results = {}
    with sync_playwright() as pw:
        browser = pw.chromium.launch(channel="chrome")
        for mode in modes:
            context = browser.new_context(viewport={"width": 1360, "height": 900}, color_scheme=mode.get("scheme", "light"),
                                          reduced_motion="reduce" if mode.get("reduced") else "no-preference")
            context.route("https://api.mistral.ai/**", lambda route: route.abort())  # a check never talks to Mistral
            if mode.get("no_storage"):
                context.add_init_script("Object.defineProperty(window, 'localStorage', { get() { throw new Error('storage blocked'); } });")
            for path in paths:
                page = context.new_page()
                errors = []
                page.on("console", lambda m, errors=errors: errors.append(f"console {m.type}: {m.text}") if m.type == "error" and "/local/" not in (m.location or {}).get("url", "") else None)
                page.on("pageerror", lambda e, errors=errors: errors.append(f"page error: {e}"))
                page.on("requestfailed", lambda r, errors=errors: errors.append(f"request failed: {r.url.split('/site/')[-1]}") if "/local/" not in r.url and not r.url.startswith(CHAT_ENDPOINT) else None)
                page.goto(path.as_uri())
                try:
                    page.wait_for_function("document.documentElement.getAttribute('data-mounted') === '1'", timeout=20000)
                except Exception:
                    errors.append("Braid.mount() never finished")
                page.wait_for_timeout(150)
                state = page.evaluate("""() => ({
                    figures: [...document.querySelectorAll('figure.fig[data-fig]')].map(f => [f.id, f.getAttribute('data-rendered')]),
                    images: [...document.images].filter(i => i.complete && i.naturalWidth === 0).map(i => i.getAttribute('src')),
                    overflow: document.documentElement.scrollWidth > document.documentElement.clientWidth + 1
                })""")
                rel = path.relative_to(SITE).as_posix()
                for fid, rendered in state["figures"]:
                    if rendered != "ok":
                        errors.append(f"figure {fid} did not draw ({rendered})")
                for src in state["images"]:
                    errors.append(f"image did not load: {src}")
                if rel in ("selftest.html", "code.html", "boards.html") or mode.get("selfcheck"):
                    checks = page.evaluate("() => Braid.selfCheck()")
                    failed = [c for c in checks if not c["ok"]]
                    results[rel] = (len(checks), len(failed))
                    for c in failed[:20]:
                        errors.append(f"self-check failed: {c.get('session') or c.get('figure')}: {c['name']} · {c.get('detail')}")
                for e in errors:
                    problems.append(f"{rel} [{mode['name']}]: {e}")
                if shots and mode["name"] == "light":
                    out = Path(shots)
                    out.mkdir(parents=True, exist_ok=True)
                    page.screenshot(path=str(out / (rel.replace("/", "__") + ".png")), full_page=True)
                if shots and mode["name"] == "dark" and rel in ("index.html", "00-entropy.html", "07-inference.html"):
                    page.screenshot(path=str(Path(shots) / (rel.replace("/", "__") + ".dark.png")), full_page=True)
                if mode["name"] == "light" and not rel.startswith("figures/"):
                    for e in page.evaluate(SPACING) + interact(page, rel) + (explore(page) if rel == "code.html" else []) + (chat(page, rel) if rel in ("index.html", "code.html") else []):
                        problems.append(f"{rel} [{mode['name']}]: {e}")
                page.close()
            context.close()
        context = browser.new_context(viewport={"width": 390, "height": 844}, device_scale_factor=2)
        context.route("https://api.mistral.ai/**", lambda route: route.abort())
        for path in paths:
            page = context.new_page()
            page.goto(path.as_uri())
            try:
                page.wait_for_function("document.documentElement.getAttribute('data-mounted') === '1'", timeout=20000)
            except Exception:
                pass
            page.wait_for_timeout(150)
            rel = path.relative_to(SITE).as_posix()
            overflow = page.evaluate("document.documentElement.scrollWidth > document.documentElement.clientWidth + 1")
            if overflow:
                wide = page.evaluate("[...document.querySelectorAll('main *')].filter(e => e.getBoundingClientRect().right > document.documentElement.clientWidth + 1 && !e.closest('.scroll, pre, .detail, .code')).slice(0, 3).map(e => e.tagName + '.' + e.className)")
                problems.append(f"{rel} [phone]: the page scrolls sideways at 390 px ({', '.join(wide)})")
            if shots and rel in ("index.html", "00-entropy.html", "07-inference.html", "05-training.html"):
                page.screenshot(path=str(Path(shots) / (rel.replace("/", "__") + ".phone.png")), full_page=False)
            page.close()
        context.close()
        browser.close()
    return results


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--shots", default=None)
    parser.add_argument("--pages", default=None)
    parser.add_argument("--prose", action="store_true")
    parser.add_argument("--quick", action="store_true", help="light mode only")
    args = parser.parse_args()
    problems, warnings = [], []
    check_prose(problems, warnings, args.prose)
    if args.prose:
        print(f"prose: {len(problems)} problems, {len(warnings)} warnings")
        for p in problems:
            print("  ✗", p)
        sys.exit(1 if problems else 0)
    check_links(problems)
    check_local(problems)
    check_lint(problems)
    check_boards(problems)
    check_size(problems)
    modes = [{"name": "light"}] if args.quick else [{"name": "light"}, {"name": "dark", "scheme": "dark"}, {"name": "reduced", "reduced": True}, {"name": "no-storage", "no_storage": True}]
    results = browse(pages(args.pages), problems, args.shots, modes)
    if not args.quick:
        webkit(pages(args.pages), problems)
    for page, (n, failed) in results.items():
        print(f"  self-check {page}: {n - failed} of {n} passed")
    print(f"prose: {len(warnings)} warnings (run --prose to list them)")
    if problems:
        print(f"{len(problems)} problems:")
        for p in problems:
            print("  ✗", p)
        sys.exit(1)
    print("check: ok")


if __name__ == "__main__":
    main()
