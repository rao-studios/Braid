CHAT_ENDPOINT = "https://api.mistral.ai/v1/chat/completions"
BUDGET = {"total": 6.0, "data": 1.8, "sources": 1.6, "fixtures": 0.4, "code": 1.0}
SOURCES_HEADER = re.compile(r"^/\* generated by Docs/site/src/sources\.py from Sources(/[A-Za-z]+)?(, Docs/site/src/trails\.json)? - do not edit \*/$")
SOURCE_GUARDS = ["window.BraidData = window.BraidData || {};", "window.BraidData.sources = window.BraidData.sources || {};"]
BANNED = ["in other words", "essentially", "basically", "note that", "it is worth", "importantly", "in this chapter", "as we will see"]


def site_files(pattern):
    for p in sorted(SITE.rglob(pattern)):
        rel = p.relative_to(SITE).as_posix()
        if any(rel.startswith(i) for i in IGNORED) or p.name.startswith("._"):
            continue
        yield p


def pages(selected=None):
    out = [p for p in site_files("*.html")]
    if selected:
        wanted = set(selected.split(","))
        out = [p for p in out if p.relative_to(SITE).as_posix() in wanted or p.name in wanted]
    return out


class Collector(html.parser.HTMLParser):
    def __init__(self):
        super().__init__()
        self.ids, self.links, self.scripts, self.styles, self.paragraphs = set(), [], [], [], []
        self._stack, self._buf, self._skip = [], [], 0

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if "id" in a:
            self.ids.add(a["id"])
        if tag == "a" and "href" in a:
            self.links.append(a["href"])
        if tag == "script":
            self.scripts.append(a)
        if tag == "link" and a.get("rel") == "stylesheet":
            self.styles.append(a.get("href", ""))
        if tag in ("details", "pre", "code", "table", "script", "style") or ("class" in a and any(c in a["class"].split() for c in ("code", "detail", "engineers", "explore", "state-box", "note", "toc"))):
            self._skip += 1
            self._stack.append(("skip", tag))
        elif tag in ("p", "figcaption"):
            self._stack.append(("para", tag))
            self._buf = []
        else:
            self._stack.append(("other", tag))

    def handle_endtag(self, tag):
        while self._stack:
            kind, t = self._stack.pop()
            if kind == "skip":
                self._skip -= 1
            if kind == "para" and t == tag and self._skip == 0:
                text = re.sub(r"\s+", " ", "".join(self._buf)).strip()
                if text:
                    self.paragraphs.append(text)
            if t == tag:
                break

    def handle_data(self, data):
        if self._skip == 0:
            self._buf.append(data)


def collect(path):
    c = Collector()
    c.feed(path.read_text(encoding="utf-8"))
    return c


IGNORED_PATHS = {}


def ignored(path):
    """True when git keeps `path` out of the repo (the local-only docs), so a link to it breaks in a clone."""
    if path not in IGNORED_PATHS:
        IGNORED_PATHS[path] = subprocess.run(["git", "-C", str(REPO), "check-ignore", "-q", str(path)]).returncode == 0
    return IGNORED_PATHS[path]


def check_links(problems):
    ids = {p: collect(p).ids for p in site_files("*.html")}
    for page, info in ((p, collect(p)) for p in site_files("*.html")):
        for href in info.links:
            if re.match(r"^(https?:|mailto:)", href):
                continue
            target, _, frag = href.partition("#")
            frag = frag.split(";")[0]
            dest = (page.parent / target).resolve() if target else page
            if target and not dest.exists():
                problems.append(f"{page.relative_to(SITE)}: link to {href} does not resolve")
                continue
            if target and ignored(dest):
                problems.append(f"{page.relative_to(SITE)}: link to {href} points at a file git ignores, which only this Mac has")
                continue
            if frag and dest.suffix == ".html" and dest.name == "code.html" and frag.startswith(("Sources/", "trail-", "q=")):
                check_explorer_fragment(page, href.partition("#")[2], problems)
            elif frag and dest.suffix == ".html" and dest in ids and frag not in ids[dest] and not frag.startswith(("fig-", "status-", "explore-")):
                problems.append(f"{page.relative_to(SITE)}: #{frag} is not an id in {dest.relative_to(SITE) if str(dest).startswith(str(SITE)) else dest}")


def check_explorer_fragment(page, frag, problems):
    """code.html#Sources/<path>.swift[:<line>|:<scope>], #trail-<trail>-<n>[;n=<k>], an old #trail-<n> or #q=<text>: what the explorer accepts."""
    where = page.relative_to(SITE)
    m = re.match(r"^trail-(?:([a-z]+(?:-[a-z]+)*)-)?(\d+)(?:;n=(\d+))?$", frag)
    if frag.startswith("trail-"):
        steps = {t["id"]: len(t["steps"]) for t in json.loads((SITE / "src" / "trails.json").read_text(encoding="utf-8"))["trails"]}
        if not m:
            problems.append(f"{where}: #{frag} is not a trail step")
        elif m.group(1) is None and not 1 <= int(m.group(2)) <= 7:
            problems.append(f"{where}: #{frag} is not one of the overview's steps 1–7")
        elif m.group(1) is not None and not (m.group(1) in steps and 1 <= int(m.group(2)) <= steps[m.group(1)]):
            problems.append(f"{where}: #{frag} is not a step of any trail")
        return
    if frag.startswith("q="):
        return
    path, _, at = frag.partition(".swift")
    src = REPO / (path + ".swift")
    if not src.is_file():
        problems.append(f"{where}: #{frag} names a file that is not in the repo")
    elif at.startswith(":") and at[1:].isdigit() and int(at[1:]) > src.read_text(encoding="utf-8").count("\n"):
        problems.append(f"{where}: #{frag} is past the end of {path}.swift")


def check_sources_file(rel, text, problems):
    """A data/sources file holds its header, two guard lines and one JSON value, and each Swift text in it equals the
    working tree. The Swift inside may say fetch( or http, so it is checked this way rather than linted."""
    lines = text.split("\n")
    if len(lines) != 5 or not SOURCES_HEADER.match(lines[0]) or lines[1:3] != SOURCE_GUARDS or lines[4] != "":
        problems.append(f"{rel}: not the shape src/sources.py writes; run src/build.sh")
        return
    m = re.match(r'^window\.BraidData\.sources\["(\w+)"\] = (.*);$', lines[3])
    if not m:
        problems.append(f"{rel}: not the shape src/sources.py writes; run src/build.sh")
        return
    value = json.loads(m.group(2))
    if json.dumps(value, ensure_ascii=False, separators=(",", ":")) != m.group(2):
        problems.append(f"{rel}: its JSON is not as src/sources.py writes it; run src/build.sh")
    module = m.group(1)
    if module == "index":
        return
    on_disk = sorted(q.relative_to(REPO).as_posix() for q in (REPO / "Sources" / module).rglob("*.swift") if not q.name.startswith("._"))
    if on_disk != [f["path"] for f in value["files"]]:
        problems.append(f"{rel}: its files differ from Sources/{module}; run src/build.sh")
    for f in value["files"]:
        src = REPO / f["path"]
        if src.is_file() and src.read_text(encoding="utf-8") != f["text"]:
            problems.append(f"{rel}: {f['path']} has changed since the site was built; run src/build.sh")


def check_lint(problems):
    for p in list(site_files("*.html")) + list(site_files("*.js")) + list(site_files("*.css")):
        text = p.read_text(encoding="utf-8")
        rel = p.relative_to(SITE).as_posix()
        if rel.startswith("data/sources/"):
            check_sources_file(rel, text, problems)
            continue
        if 'type="module"' in text or "type='module'" in text:
            problems.append(f"{rel}: an ES module (file:// blocks them)")
        if rel == "js/chat.js":
            # The chat orb is the site's one network call: to Mistral, and only when the reader sends a message.
            urls = set(re.findall(r"https?://[^\s\"'`)]+", text))
            if urls != {CHAT_ENDPOINT}:
                problems.append(f"{rel}: the chat may call {CHAT_ENDPOINT} and nothing else; it names {sorted(urls)}")
        elif re.search(r"\bfetch\(", text):
            problems.append(f"{rel}: fetch() (file:// blocks it)")
        for m in re.finditer(r"""(?:src|href)=["'](https?://[^"']+)""", text):
            problems.append(f"{rel}: a network URL {m.group(1)}")
        for m in re.finditer(r"url\((['\"]?)(https?://[^)'\"]+)", text):
            problems.append(f"{rel}: a network URL {m.group(2)}")
        if re.search(r"""(?:src|href)=["']/(?!/)""", text):
            problems.append(f"{rel}: an absolute path")
        if "@import" in text and "http" in text:
            problems.append(f"{rel}: @import from the network")


def check_prose(problems, warnings, verbose):
    glossary = ["H_lm", "H_knn", "λ", "τ", "κ"]
    for p in site_files("*.html"):
        rel = p.relative_to(SITE).as_posix()
        if rel.startswith("figures/") or rel in ("selftest.html",):
            continue
        for para in collect(p).paragraphs:
            low = para.lower()
            for phrase in BANNED:
                if re.search(r"\b" + re.escape(phrase) + r"\b", low):
                    problems.append(f"{rel}: “{phrase}” in “{para[:70]}…”")
            if re.search(r"\([^)]*[a-z][^)]*\)", para) and not re.search(r"\b[A-Za-z_]+\([^)]*\)", para):
                problems.append(f"{rel}: a parenthesis inside a paragraph: “{para[:70]}…”")
            sentences = [s for s in re.split(r"(?<=[.!?])\s+(?=[A-Z“\"])", para) if s]
            for s in sentences:
                if len(s.split()) > 30:
                    warnings.append(f"{rel}: a sentence of {len(s.split())} words: “{s[:60]}…”")
            if len(sentences) > 5:
                warnings.append(f"{rel}: a paragraph of {len(sentences)} sentences: “{para[:50]}…”")
            numbers = re.findall(r"(?<![\w.])\d[\d,.]*\d|\b\d\b", para)
            if len(set(numbers)) > 2:
                warnings.append(f"{rel}: {len(set(numbers))} numbers in one paragraph: “{para[:50]}…”")
    if verbose:
        for w in warnings:
            print("  prose:", w)


def check_local(problems):
    """Docs/site/local/ holds the chat orb's key (src/chatkey.py). Git must ignore it in either spelling of the folder."""
    for spelling in ("Docs/site/local/chat.js", "docs/site/local/chat.js"):
        if subprocess.run(["git", "-C", str(REPO), "check-ignore", "-q", spelling]).returncode != 0:
            problems.append(f"{spelling} is not ignored by git; it holds an API key")
    tracked = subprocess.run(["git", "-C", str(REPO), "ls-files", "Docs/site/local", "docs/site/local"], capture_output=True, text=True).stdout.split()
    if tracked:
        problems.append(f"git tracks {', '.join(tracked)}, which holds an API key; remove it from the index and rotate the key")


def check_boards(problems):
    """The panels js/boards/board-N.js define are the ones boards.html places, once each; every data-board on every page is defined; the old crops are gone."""
    defined = {}
    for js in sorted((SITE / "js" / "boards").glob("board-*.js")):
        for m in re.finditer(r'boards\.define\("([a-z0-9-]+)"', js.read_text(encoding="utf-8")):
            if m.group(1) in defined:
                problems.append(f"boards: {m.group(1)} is defined twice, in {defined[m.group(1)]} and {js.name}")
            defined[m.group(1)] = js.name
    placed = re.findall(r'data-board="([a-z0-9-]+)"', (SITE / "boards.html").read_text(encoding="utf-8"))
    for pid in sorted(set(defined) - set(placed)):
        problems.append(f"boards.html: the panel {pid} ({defined[pid]}) has no cell")
    for pid in sorted(set(placed) - set(defined)):
        problems.append(f"boards.html: {pid} is not a panel any board file defines")
    for pid in sorted({x for x in placed if placed.count(x) > 1}):
        problems.append(f"boards.html: {pid} has {placed.count(pid)} cells")
    for page in site_files("*.html"):
        rel = page.relative_to(SITE).as_posix()
        if rel.startswith("figures/") or rel == "boards.html":
            continue
        for pid in re.findall(r'data-board="([a-z0-9-]+)"', page.read_text(encoding="utf-8")):
            if pid not in defined:
                problems.append(f"{rel}: data-board {pid} is not a panel any board file defines")
    for stale in ("boards", "src/boards.py", "src/crops.json"):
        if (SITE / stale).exists():
            problems.append(f"{stale} was retired on 2026-10-19 and should not exist")
    print(f"  boards: {len(defined)} panels defined, {len(placed)} placed")


def check_size(problems):
    tracked = subprocess.run(["git", "-C", str(REPO), "ls-files", "--others", "--cached", "--exclude-standard", "Docs/site", "docs/site"],
                             capture_output=True, text=True).stdout.split()
    sizes = {k: 0 for k in BUDGET}
    for f in sorted(set(tracked)):
        p = REPO / f
        if not p.is_file():
            continue
        rel = f.split("site/", 1)[1]
        n = p.stat().st_size
        sizes["total"] += n
        parts = rel.split("/")
        key = "sources" if parts[:2] == ["data", "sources"] else parts[0]
        if key in sizes:
            sizes[key] += n
        elif rel.endswith((".html", ".css", ".js")):
            sizes["code"] += n
    for k, limit in BUDGET.items():
        mb = sizes[k] / 1048576
        mark = "ok" if mb <= limit else "OVER"
        print(f"  size {k:9} {mb:6.2f} MB of {limit} MB {mark}")
        if mb > limit:
            problems.append(f"size: {k} is {mb:.2f} MB, over {limit} MB")


def webkit(paths, problems):
    """Every page once in WebKit, Safari's engine, where file:// pages open when Safari is the default browser."""
    from playwright.sync_api import sync_playwright
    with sync_playwright() as pw:
        try:
            browser = pw.webkit.launch()
        except Exception as error:
            print(f"  webkit: not installed, skipped ({str(error).splitlines()[0][:80]})")
            return
        page_count = 0
        for path in paths:
            page = browser.new_page(viewport={"width": 1360, "height": 900})
            errors = []
            page.on("pageerror", lambda e, errors=errors: errors.append(f"page error: {e}"))
            page.on("console", lambda m, errors=errors: errors.append(f"console {m.type}: {m.text}") if m.type == "error" else None)
            page.goto(path.as_uri())
            try:
                page.wait_for_function("document.documentElement.getAttribute('data-mounted') === '1'", timeout=20000)
            except Exception:
                errors.append("Braid.mount() never finished")
            bad = page.evaluate("[...document.querySelectorAll('figure.fig[data-fig]')].filter(f => f.getAttribute('data-rendered') !== 'ok').map(f => f.id)")
            errors += [f"figure {f} did not draw" for f in bad]
            if path.name in ("selftest.html", "code.html", "boards.html"):
                failed = page.evaluate("Braid.selfCheck().filter(c => !c.ok).map(c => (c.figure || c.session) + ': ' + c.name)")
                errors += [f"self-check failed: {f}" for f in failed]
            for e in errors:
                problems.append(f"{path.relative_to(SITE).as_posix()} [webkit]: {e}")
            page_count += 1
            page.close()
        browser.close()
        print(f"  webkit: {page_count} pages")


