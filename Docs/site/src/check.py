def interact(page, rel):
    """Drags every visible slider the way a reader does, and types into the record's text box."""
    errors = []
    sliders = page.evaluate("""() => [...document.querySelectorAll('figure.fig .fig-body input[type=range]')]
        .filter(i => i.offsetParent !== null && !i.closest('details:not([open])')).map(i => [i.closest('figure.fig').id, i.getAttribute('aria-label')])""")
    for fid, label in sliders:
        el = page.query_selector(f'figure#{fid} input[type=range][aria-label="{label}"]')
        if not el:
            continue
        el.scroll_into_view_if_needed()
        box = el.bounding_box()
        info = el.evaluate("e => ({ v: +e.value, min: +e.min, max: +e.max, out: (e.closest('label').querySelector('output') || {}).textContent })")
        if not box or box["width"] < 20 or info["max"] <= info["min"]:
            continue
        thumb = 16
        frac = (info["v"] - info["min"]) / (info["max"] - info["min"])
        goal = 0.85 if frac < 0.5 else 0.15
        x0, x1, y = box["x"] + thumb / 2 + frac * (box["width"] - thumb), box["x"] + thumb / 2 + goal * (box["width"] - thumb), box["y"] + box["height"] / 2
        el.evaluate("e => { e.__probe = 1; }")
        before = page.evaluate(FIGURE_BODY, fid)
        page.mouse.move(x0, y)
        page.mouse.down()
        live = None
        for i in range(1, 11):
            page.mouse.move(x0 + (x1 - x0) * i / 10, y)
            page.wait_for_timeout(25)
            if i == 6:
                live = el.evaluate("e => e.isConnected && e.__probe === 1") and page.evaluate(FIGURE_BODY, fid) != before
        page.mouse.up()
        page.wait_for_timeout(60)
        after = el.evaluate("e => ({ same: e.isConnected && e.__probe === 1, v: +e.value, out: (e.closest('label').querySelector('output') || {}).textContent })")
        where = f"{fid} “{label}”"
        if not after["same"]:
            errors.append(f"slider {where} was replaced during the drag, so the knob stopped following the cursor")
            continue
        target = info["min"] + goal * (info["max"] - info["min"])
        if abs(after["v"] - target) > 0.12 * (info["max"] - info["min"]):
            errors.append(f"slider {where} ended at {after['v']} after a drag toward {target:.3g} (from {info['v']})")
        if not live:
            errors.append(f"slider {where}: the figure did not redraw while the knob was held")
        if after["out"] == info["out"]:
            errors.append(f"slider {where}: its readout stayed “{info['out']}” through the drag")
    area = page.query_selector('figure.fig .fig-body textarea')
    if area and area.is_visible() and not area.evaluate("e => !!e.closest('details:not([open])')"):
        fid = area.evaluate("e => e.closest('figure.fig').id")
        area.scroll_into_view_if_needed()
        area.click()
        area.evaluate("e => { e.__probe = 1; e.setSelectionRange(e.value.length, e.value.length); }")
        before = page.evaluate(FIGURE_BODY, fid)
        page.keyboard.type("abc", delay=40)
        page.wait_for_timeout(80)
        got = area.evaluate("e => ({ same: e.isConnected && e.__probe === 1, focused: document.activeElement === e, end: e.selectionStart === e.value.length && e.selectionEnd === e.value.length, tail: e.value.slice(-3) })")
        if not (got["same"] and got["focused"] and got["end"] and got["tail"] == "abc"):
            errors.append(f"typing into {fid}'s text box lost it: {got}")
        elif page.evaluate(FIGURE_BODY, fid) == before:
            errors.append(f"typing into {fid}'s text box did not redraw the figure")
    return errors


def chat(page, rel):
    """The orb, used: half seen, whole under the pointer, open into a chat, answer through a stand-in, start a new chat, close back."""
    errors = []
    try:
        page.wait_for_selector(".chat-orb", state="attached", timeout=5000)
    except Exception:
        return ["the chat orb never appeared"]
    page.evaluate("window.scrollTo(0, 0)")
    orb = page.query_selector(".chat-orb")
    rest = float(orb.evaluate("e => getComputedStyle(e).opacity"))
    orb.hover()
    page.wait_for_timeout(350)
    lit = float(orb.evaluate("e => getComputedStyle(e).opacity"))
