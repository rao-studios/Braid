#!/usr/bin/env python3
"""Checks the tutorial site the way a reader meets it: from file://, in Google Chrome and in WebKit, Safari's engine.

    python3 -I Docs/site/src/check.py                            # every page, light and dark, reduced motion, storage blocked
    python3 -I Docs/site/src/check.py --shots Docs/site/.check/shots    # also full-page and figure screenshots to look at
    python3 -I Docs/site/src/check.py --pages 00-entropy.html,07-inference.html
    python3 -I Docs/site/src/check.py --prose                    # only the prose rules, with every warning listed

With Playwright's WebKit installed (`python3 -m playwright install webkit`), every page also opens once in WebKit, Safari's engine.

Per page: no console error, page error or failed request; every <figure data-fig> drew (data-rendered="ok"); every
image loaded; and, on the self-test page, every check in Braid.selfCheck() passed. In light mode, also the spacing
(every floated figure keeps 24 px from its text and from what follows; blocks that share horizontal space keep 12 px
between them) and the controls (every visible slider is dragged with the mouse in ten steps and must stay the same
element under the cursor while its figure redraws; typing into the record's text box keeps the caret at the end).
Then, over the files: every
relative link resolves and every #id exists; no ES module, no fetch, no network URL, no absolute path; the prose
rules; and the size budget. Exits 1 on any failure, after printing all of them.
"""

