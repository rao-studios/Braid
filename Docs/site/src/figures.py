#!/usr/bin/env python3
"""Writes one embeddable page per figure, from the figures the chapter pages already hold.

    python3 -I Docs/site/src/figures.py

Every <figure class="fig" data-fig> on a chapter page, and every board panel <figure class="board"
data-board>, becomes Docs/site/figures/<id>.html: the same figure with the same settings and caption,
the same scripts, and no site chrome, for an iframe or an export. The registry is the pages themselves,
so a figure page can never drift from its chapter; boards.html comes last, so a panel a chapter shows
links back to that chapter.
Settings can be overridden in the URL: figures/<id>.html?s=joltvault&i=12&theme=dark&export=1.

Outputs: Docs/site/figures/<id>.html and Docs/site/figures/index.js (window.BraidData.figureIndex).
"""

import html
import html.parser
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
SITE = REPO / "Docs" / "site"
OUT = SITE / "figures"
PAGES = ["index.html", "00-entropy.html"] + [f"{n:02d}-{s}.html" for n, s in [(1, "aii"), (2, "records"), (3, "corpus"), (4, "commons"), (5, "training"), (6, "provenance"),
                                                         (7, "inference"), (8, "trace"), (9, "ssd"), (10, "verify")]] + ["aii-storage.html", "boards.html"]


class Figures(html.parser.HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.figures, self.scripts, self.title = [], [], ""
        self._fig, self._depth, self._cap, self._in_title = None, 0, None, False

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "title":
            self._in_title = True
        if tag == "script" and a.get("src"):
            self.scripts.append(a["src"])
        if tag == "figure" and "fig" in (a.get("class") or "").split() and a.get("data-fig"):
            self._fig = {"id": a.get("id", "").replace("fig-", "", 1) or a["data-fig"], "attrs": {k: v for k, v in a.items() if k.startswith("data-")}, "caption": ""}
            self._depth = 1
            return
        if tag == "figure" and "board" in (a.get("class") or "").split() and a.get("data-board"):
            attrs = {"data-fig": "board:" + a["data-board"]}
            if a.get("data-caption"):
                attrs["data-caption"] = a["data-caption"]
            self._fig = {"id": a["data-board"], "attrs": attrs, "caption": a.get("data-caption", ""), "board": True}
            self._depth = 1
            return
        if self._fig is not None:
            if tag == "figure":
                self._depth += 1
            if tag == "figcaption" and self._depth == 1:
                self._cap = []

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False
        if self._fig is None:
            return
        if tag == "figcaption" and self._cap is not None:
            self._fig["caption"] = re.sub(r"\s+", " ", "".join(self._cap)).strip()
            self._cap = None
        if tag == "figure":
            self._depth -= 1
            if self._depth == 0:
                self.figures.append(self._fig)
                self._fig = None

    def handle_data(self, data):
        if self._in_title:
            self.title += data
        if self._cap is not None:
            self._cap.append(data)


PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<!-- generated by Docs/site/src/figures.py from {chapter} - do not edit -->
<title>{title} · Braid, step by step</title>
<meta name="description" content="{caption_attr}">
<link rel="stylesheet" href="../css/tokens.css">
<link rel="stylesheet" href="../css/site.css">
<link rel="stylesheet" href="../css/figure.css">
</head>
<body class="embed" data-root="../">
<figure class="fig" id="fig-{id}"{attrs}>
<figcaption>{caption} <a href="../{chapter}#fig-{id}" target="_top">In context</a></figcaption>
</figure>
{scripts}
<script>Braid.mount();</script>
</body>
</html>
"""


def main():
    OUT.mkdir(exist_ok=True)
    seen, index = {}, []
    for name in PAGES:
        path = SITE / name
        if not path.exists():
            continue
        parser = Figures()
        parser.feed(path.read_text(encoding="utf-8"))
        scripts = [s for s in parser.scripts if not s.startswith("http")]
        for fig in parser.figures:
            fid = fig["id"]
            if fid in seen:
                continue
            seen[fid] = name
            attrs = "".join(f' {k}="{html.escape(v, quote=True)}"' for k, v in fig["attrs"].items())
            title = fig["attrs"].get("data-title") or fid.replace("-", " ").capitalize()
            body = PAGE.format(chapter=name, title=html.escape(title), caption_attr=html.escape(fig["caption"], quote=True), id=fid, attrs=attrs,
                               caption=html.escape(fig["caption"]), scripts="\n".join(f'<script src="../{s}"></script>' for s in scripts))
            (OUT / f"{fid}.html").write_text(body, encoding="utf-8")
            index.append({"id": fid, "fig": fig["attrs"]["data-fig"], "chapter": name, "title": title, "caption": fig["caption"],
                          "params": {k[5:]: v for k, v in fig["attrs"].items() if k not in ("data-fig", "data-title")}})
    for old in OUT.glob("*.html"):
        if old.stem not in seen:
            old.unlink()
    (OUT / "index.js").write_text("/* generated by Docs/site/src/figures.py - do not edit */\nwindow.BraidData = window.BraidData || {};\nwindow.BraidData.figureIndex = "
                                  + json.dumps(index, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    print(f"wrote {len(index)} figure pages to Docs/site/figures")


if __name__ == "__main__":
    sys.exit(main())
