def git_head(repo):
    try:
        return subprocess.run(["git", "-C", str(repo), "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return None


def git_dirty(repo, path):
    try:
        return bool(subprocess.run(["git", "-C", str(repo), "status", "--porcelain", "--", path], capture_output=True, text=True, check=True).stdout.strip())
    except Exception:
        return False


def js_file(path, module, value):
    """Writes the generated shape check.py pins: a header, two guard lines and one assignment."""
    body = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    source = "Sources/" + module if module != "index" else "Sources, Docs/site/src/trails.json"
    text = ("/* generated by Docs/site/src/sources.py from " + source + " - do not edit */\n"
            "window.BraidData = window.BraidData || {};\n"
            "window.BraidData.sources = window.BraidData.sources || {};\n"
            f"window.BraidData.sources[{json.dumps(module)}] = {body};\n")
    return text


# MARK: The lexer

CODE_STOP = re.compile(r'[/"#()\[\]{}\n]')
STRING_STOP = re.compile(r'["\\\n]')
COMMENT_STOP = re.compile(r"/\*|\*/|\n")
MARK = re.compile(r"//\s*MARK:\s*-?\s*(.*)")


def lex(text, where):
    """One pass over a file. Returns the text with strings and comments blanked to spaces (newlines and the code
    inside interpolations kept), every brace with its line and the paren, bracket and frame depth it sits at, the
    lines that are /// doc comments, and the MARK lines."""
    out = list(text)
    braces, doc, marks = [], set(), []
    stack = [["c", 0, 0]]  # code frames ["c", paren, bracket]; strings ["s", hashes, multiline]; block comments ["m", depth]
    i, n, line = 0, len(text), 1

    def blank(a, b):
        out[a:b] = " " * (b - a)

    while i < n:
        frame = stack[-1]
        if frame[0] == "c":
            m = CODE_STOP.search(text, i)
            if not m:
                break
            j = m.start()
            ch = text[j]
            if ch == "\n":
                line += 1
                i = j + 1
            elif ch == "/":
                nxt = text[j + 1:j + 2]
                if nxt == "/":
                    e = text.find("\n", j)
                    e = n if e < 0 else e
                    comment = text[j:e]
                    if comment.startswith("///") and not comment.startswith("////"):
                        doc.add(line)
                    mm = MARK.match(comment)
                    if mm:
                        marks.append([line, mm.group(1).strip()])
                    blank(j, e)
                    i = e
                elif nxt == "*":
                    stack.append(["m", 1])
                    blank(j, j + 2)
                    i = j + 2
                else:
                    i = j + 1
            elif ch == "#":
                k = j
                while k < n and text[k] == "#":
                    k += 1
                if k < n and text[k] == '"':
                    multi = text.startswith('"""', k)
                    end = k + (3 if multi else 1)
                    blank(j, end)
                    stack.append(["s", k - j, multi])
                    i = end
                else:
                    i = k
            elif ch == '"':
                multi = text.startswith('"""', j)
                end = j + (3 if multi else 1)
                blank(j, end)
                stack.append(["s", 0, multi])
                i = end
            elif ch == "(":
                frame[1] += 1
                i = j + 1
            elif ch == ")":
                if frame[1] == 0 and len(stack) > 1:
                    blank(j, j + 1)  # the end of an interpolation
                    stack.pop()
                else:
                    frame[1] -= 1
                i = j + 1
            elif ch == "[":
                frame[2] += 1
                i = j + 1
            elif ch == "]":
                frame[2] -= 1
                i = j + 1
            else:
                braces.append((j, ch, line, frame[1], frame[2], len(stack)))
                i = j + 1
        elif frame[0] == "s":
            m = STRING_STOP.search(text, i)
            if not m:
                fail(f"{where}:{line}: a string never ends")
            j = m.start()
            blank(i, j)
            ch = text[j]
            hashes = frame[1]
            if ch == "\n":
                if not frame[2]:
                    fail(f"{where}:{line}: a string runs past the end of its line")
                line += 1
                i = j + 1
            elif ch == "\\":
                if text.startswith("#" * hashes + "(", j + 1):
                    blank(j, j + 2 + hashes)
                    stack.append(["c", 0, 0])
                    i = j + 2 + hashes
                elif hashes == 0:
                    if text[j + 1:j + 2] == "\n":
                        line += 1
                        blank(j, j + 1)
                    else:
                        blank(j, j + 2)
                    i = j + 2
                else:
                    blank(j, j + 1)
                    i = j + 1
            elif frame[2] and text.startswith('"""' + "#" * hashes, j):
                blank(j, j + 3 + hashes)
                stack.pop()
                i = j + 3 + hashes
            elif not frame[2] and text.startswith('"' + "#" * hashes, j):
                blank(j, j + 1 + hashes)
                stack.pop()
                i = j + 1 + hashes
            else:
                blank(j, j + 1)
                i = j + 1
        else:
            m = COMMENT_STOP.search(text, i)
            if not m:
                fail(f"{where}:{line}: a block comment never ends")
            j = m.start()
            blank(i, j)
            if text[j] == "\n":
                line += 1
                i = j + 1
            else:
                blank(j, j + 2)
                frame[1] += 1 if text[j] == "/" else -1
                if frame[1] == 0:
                    stack.pop()
                i = j + 2
    if len(stack) != 1 or stack[0][1] or stack[0][2]:
        fail(f"{where}: ends inside {'a string' if stack[-1][0] == 's' else 'a comment' if stack[-1][0] == 'm' else 'an open paren or bracket'}")
    return "".join(out), braces, doc, marks


# MARK: Declarations

MODIFIERS = ("public|private|fileprivate|internal|open|package|static|class|final|mutating|nonmutating|override|nonisolated|"
             "lazy|weak|unowned|indirect|convenience|required|dynamic|optional")
DECL = re.compile(r"""[ \t]*
    (?P<attrs>(?:@[A-Za-z_]\w*(?:\([^()\n]*\))?[ \t]+)*)
    (?P<mods>(?:(?:""" + MODIFIERS + r""")(?:\([^)\n]*\))?[ \t]+)*)
    (?P<kw>func|init|deinit|subscript|var|let|struct|class|enum|actor|extension|protocol)(?![\w])""", re.X)
ATTRIBUTE_LINE = re.compile(r"^[ \t]*@[A-Za-z_]\w*(?:\([^)]*\))?[ \t]*$")
ASSIGN = re.compile(r"(?<![=!<>])=(?![=>])")
IDENT = r"(?:`[^`]+`|[A-Za-z_]\w*)"


def top_level(s):
    """The text of `s` outside every (), [] and {}."""
    out, depth = [], 0
    for ch in s:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif depth == 0:
            out.append(ch)
    return "".join(out)


def split_top(s, sep):
    parts, cur, depth = [], [], 0
    for ch in s:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == sep and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    parts.append("".join(cur))
    return parts


def closing_paren(s, p):
    depth = 0
    for k in range(p, len(s)):
        if s[k] == "(":
            depth += 1
        elif s[k] == ")":
            depth -= 1
            if depth == 0:
                return k
    return None


def skip_angles(s, p):
    depth = 0
    for k in range(p, len(s)):
        if s[k] == "<":
            depth += 1
        elif s[k] == ">" and s[k - 1] != "-":
            depth -= 1
            if depth == 0:
                return k + 1
    return None


def first_top(s, ch):
    depth = 0
    for k, c in enumerate(s):
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == ch and depth == 0:
            return k
    return -1


def parameters(text):
    """[(label, has default, is a closure, is variadic)] from a declaration's parameter list. A comma inside a generic
    type cuts a fragment with no colon, which is dropped."""
    out = []
    for frag in split_top(text, ","):
        k = first_top(frag, ":")
        if k < 0:
            continue
        words = frag[:k].split()
        if not words or len(words) > 2 or not re.fullmatch(r"_|`?[A-Za-z_]\w*`?", words[0]):
            continue
        rest = top_level(frag[k + 1:])
        out.append((words[0].strip("`"), bool(ASSIGN.search(rest)), "->" in rest, ASSIGN.split(rest)[0].rstrip().endswith("...")))
    return out


def shape(kw, rest):
    """Checks what follows a declaration keyword up to its brace (or the end of a requirement). Returns the name and
    parameters, or None when the brace is not this declaration's."""
    if kw in ("func", "init", "subscript"):
        if kw == "func":
            m = re.match(r"\s*(" + IDENT + r"|[-+*/<>=!%&|^~?.]+)\s*", rest)
            if not m:
                return None
            name, p = m.group(1).strip("`"), m.end()
        elif kw == "init":
            m = re.match(r"[?!]?\s*", rest)
            name, p = "init", m.end()
        else:
            m = re.match(r"\s*", rest)
            name, p = "subscript", m.end()
        if rest[p:p + 1] == "<":
            p = skip_angles(rest, p)
            if p is None:
                return None
            p += len(rest[p:]) - len(rest[p:].lstrip())
        if rest[p:p + 1] != "(":
            return None
        q = closing_paren(rest, p)
        if q is None or ASSIGN.search(top_level(rest[q + 1:])):
            return None
        return {"name": name, "params": parameters(rest[p + 1:q]), "operator": bool(re.fullmatch(r"[-+*/<>=!%&|^~?.]+", name))}
    if kw == "deinit":
        return {"name": "deinit", "params": []} if not rest.strip() else None
    if kw == "var":
        if "\n" in rest.strip() or ASSIGN.search(top_level(rest)):
            return None
        m = re.match(r"\s*(" + IDENT + r")\s*:\s*\S", rest)
        return {"name": m.group(1).strip("`")} if m else None
    if kw == "let":
        return None
    if kw == "extension":
        m = re.match(r"\s*([A-Za-z_][\w.]*)", rest)
        return {"name": m.group(1)} if m and not ASSIGN.search(top_level(rest)) else None
    m = re.match(r"\s*(" + IDENT + r")", rest)
    return {"name": m.group(1).strip("`")} if m and not ASSIGN.search(top_level(rest)) else None


def find_decl(blank, start, brace):
    """The declaration a brace opens, read backwards from the brace over the text since the last brace at the same
    level. The last line (or `;` statement) that begins with a declaration keyword decides: either it is this brace's
    declaration, or the brace is a block."""
    head = blank[start:brace]
    starts = [0] + [k + 1 for k, ch in enumerate(head) if ch == "\n" or ch == ";"]
    for s in reversed(starts):
        m = DECL.match(head, s)
        if not m:
            continue
        info = shape(m.group("kw"), head[m.end():])
        if info is None:
            return None
        lead = len(m.group(0)) - len(m.group(0).lstrip())
        info.update(kw=m.group("kw"), mods=" ".join(m.group("mods").split()), attrs=m.group("attrs").split(),
                    offset=start + s + lead, kw_offset=start + m.start("kw"))
        return info
    return None


# MARK: Files

class SwiftFile:
    """One Swift file, lexed and walked: its scopes in source order, its header, its doc comments and its MARKs."""

    def __init__(self, text, path, module, header=True):
        self.text, self.path, self.module = text, path, module
        self.blank, self.braces, self.doc, self.marks = lex(text, path)
        self.starts = [0] + [m.end() for m in re.finditer("\n", text)]
        self.lines = text.split("\n")
        self.header = self.read_header() if header else None
        self.scopes = self.walk()
        self.check_counts()

    def line_of(self, offset):
        return bisect.bisect_right(self.starts, offset)

    def read_header(self):
        lines, name = self.lines, Path(self.path).name
        k = 0
        while k < len(lines) and lines[k].startswith("//"):
            k += 1
        if k < 5 or lines[0] != "//" or lines[1] != "//  " + name or lines[2] != "//  " + self.module:
            fail(f"{self.path}: the header must open with //, //  {name}, //  {self.module}")
        tags = [(i + 1, m.group(1)) for i in range(k) for m in [re.match(r"//  (WHAT|PIN|IN|OUT):", lines[i])] if m]
        if not tags or tags[0][1] != "WHAT":
            fail(f"{self.path}: the header has no WHAT")
        ranges = {"what": None, "pin": None, "in": None, "out": None}
        for n, (first, tag) in enumerate(tags):
            last = tags[n + 1][0] - 1 if n + 1 < len(tags) else k
            while last > first and lines[last - 1].strip() == "//":
                last -= 1
            ranges[tag.lower()] = [first, last]
        return dict(lines=[1, k], **ranges)

    def walk(self):
        blank, raw = self.blank, []
        stack, boundary = [], 0
        for off, ch, line, paren, bracket, depth in self.braces:
            level = depth == 1 and paren == 0 and bracket == 0
            if ch == "{":
                info = find_decl(blank, boundary, off) if level else None
                if info:
                    info.update(parent=next((s for s in reversed(stack) if s is not None), -1), brace_off=off,
                                brace=[line, off - self.starts[line - 1]], end=None, end_off=None, requirement=False)
                    raw.append(info)
                    stack.append(len(raw) - 1)
                else:
                    stack.append(None)
            else:
                if not stack:
                    fail(f"{self.path}:{line}: a closing brace with nothing open")
                top = stack.pop()
                if top is not None:
                    raw[top]["end"], raw[top]["end_off"] = line, off
            if level:
                boundary = off + 1
        if stack:
            fail(f"{self.path}: {len(stack)} braces never close")
        self.requirements(raw)
        for info in raw:
            first = self.line_of(info["offset"])
            info["sig"] = self.line_of(info["kw_offset"])
            while first > 1 and ATTRIBUTE_LINE.match(self.blank_line(first - 1)):
                first -= 1
            info["decl"] = first
            info["head_off"] = self.starts[first - 1]
        order = sorted(range(len(raw)), key=lambda k: (raw[k]["decl"], raw[k]["kw_offset"]))
        local = {old: new for new, old in enumerate(order)}
        scopes = []
        for old in order:
            info = dict(raw[old])
            info["parent"] = local[info["parent"]] if info["parent"] >= 0 else -1
            scopes.append(info)
        for sc in scopes:
            kind = KIND[sc["kw"]]
            sc["kind"] = kind
            doc_last = sc["decl"] - 1
            doc_first = doc_last
            while doc_first >= 1 and doc_first in self.doc:
                doc_first -= 1
            sc["doc"] = [doc_first + 1, doc_last] if doc_first < doc_last else None
            flags = 0
            parent = scopes[sc["parent"]] if sc["parent"] >= 0 else None
            if sc["requirement"] or (kind == "v" and parent and parent["kw"] == "protocol"):
                flags |= REQUIREMENT
                sc["requirement"] = True
            if sc.get("operator"):
                flags |= OPERATOR
            p = sc["parent"]
            while p >= 0:
                if scopes[p]["kind"] in "fidsv":
                    flags |= LOCAL
                    break
                p = scopes[p]["parent"]
            if sc["brace"] and sc["end"] == sc["brace"][0]:
                flags |= ONE_LINE
            sc["flags"] = flags
            sc["cases"] = self.cases(sc) if kind == "E" else None
        return scopes

    def blank_line(self, n):
        return self.blank[self.starts[n - 1]:(self.starts[n] - 1 if n < len(self.starts) else len(self.blank))]

    def depth_at(self, offset):
        depth = 0
        for off, ch, *_ in self.braces:
            if off >= offset:
                break
            depth += 1 if ch == "{" else -1
        return depth

    def requirements(self, raw):
        """A protocol's func, init and subscript requirements have no brace of their own; read them from its body."""
        for p in [k for k, info in enumerate(raw) if info["kw"] == "protocol"]:
            proto = raw[p]
            inner = self.depth_at(proto["brace_off"] + 1)
            for n in range(proto["brace"][0] + 1, proto["end"]):
                s = self.starts[n - 1]
                if self.depth_at(s) != inner:
                    continue
                m = DECL.match(self.blank, s)
                if not m or m.group("kw") not in ("func", "init", "subscript") or self.line_of(m.start("kw")) != n:
                    continue
                open_ = self.blank.find("(", m.end())
                close = closing_paren(self.blank, open_) if open_ >= 0 else None
                if close is None:
                    fail(f"{self.path}:{n}: a requirement's parameters never close")
                end_line = self.line_of(close)
                stop = self.starts[end_line] - 1 if end_line < len(self.starts) else len(self.blank)
                info = shape(m.group("kw"), self.blank[m.end():stop])
                if info is None:
                    fail(f"{self.path}:{n}: a requirement this parser cannot read")
                lead = len(m.group(0)) - len(m.group(0).lstrip())
                info.update(kw=m.group("kw"), mods=" ".join(m.group("mods").split()), attrs=m.group("attrs").split(),
                            offset=s + lead, kw_offset=m.start("kw"), parent=p, brace_off=None, brace=None,
                            end=end_line, end_off=stop, requirement=True)
                raw.append(info)

    def cases(self, enum):
        inner = self.depth_at(enum["brace_off"] + 1)
        names = []
        for n in range(enum["brace"][0] + 1, (enum["end"] or 0)):
            s = self.starts[n - 1]
            m = re.match(r"[ \t]*(?:indirect[ \t]+)?case[ \t]+(.*)", self.blank_line(n))
            if not m or self.depth_at(s) != inner:
                continue
            for part in split_top(m.group(1), ","):
                mm = re.match(r"\s*(" + IDENT + ")", part)
                if mm:
                    names.append(mm.group(1).strip("`"))
        return names

    def check_counts(self):
        """The walk and a plain count of the keywords must agree, file by file."""
        blank, got = self.blank, Counter(sc["kind"] for sc in self.scopes)
        want = {
            "f": len(re.findall(r"\bfunc\s", blank)),
            "i": len(re.findall(r"(?<![.\w])init[?!]?\s*(?:<[^>\n]*>)?\s*\(", blank)),
            "s": len(re.findall(r"(?<![.\w])subscript\s*\(", blank)),
            "d": len(re.findall(r"\bdeinit\b", blank)),
            "S": len(re.findall(r"\bstruct\s+[A-Z_`]", blank)),
            "E": len(re.findall(r"\benum\s+[A-Z_`]", blank)),
            "A": len(re.findall(r"\bactor\s+[A-Z_`]", blank)),
            "P": len(re.findall(r"\bprotocol\s+[A-Z_`]", blank)),
            "X": len(re.findall(r"\bextension\s+[A-Z_`]", blank)),
            "C": len(re.findall(r"\bclass\s+(?!func\b|var\b|let\b)[A-Z_`]", blank)),
        }
        for kind, n in want.items():
            if got[kind] != n:
                fail(f"{self.path}: the walk found {got[kind]} {kind!r} declarations, the keyword count {n}; run --dump on it")

    def qualified(self, k):
        names = []
        while k >= 0:
            names.append(self.scopes[k]["name"])
            k = self.scopes[k]["parent"]
        return ".".join(reversed(names))

    def ids(self):
        """Stable ids: the path without Sources/, then the qualified name, with the argument labels for callables."""
        out, seen = [], Counter()
        rel = self.path[len("Sources/"):] if self.path.startswith("Sources/") else self.path
        for k, sc in enumerate(self.scopes):
            q = self.qualified(k)
            if sc["kind"] in CALLABLE:
                q += "(" + "".join(label + ":" for label, *_ in sc["params"]) + ")"
            elif sc["kind"] == "X":
                q = "extension:" + q
            base = rel + ":" + q
            seen[base] += 1
            out.append(base if seen[base] == 1 else f"{base}~{seen[base]}")
        return out

    def record(self, first):
        """What the page ships for this file: the scopes as compact arrays, then the text, verbatim."""
        rows = []
        for sc in self.scopes:
            row = [sc["kind"], sc["name"], [p[0] for p in sc["params"]] if sc["kind"] in CALLABLE else None, sc["mods"],
                   sc["decl"], sc["sig"], sc["brace"], sc["end"], sc["doc"], sc["parent"], sc["flags"]]
            if sc["kind"] == "E":
                row.append(sc["cases"])
            rows.append(row)
        return {"path": self.path, "lines": len(self.lines) - (1 if self.text.endswith("\n") else 0), "bytes": len(self.text.encode("utf-8")),
                "header": self.header, "marks": self.marks, "first": first, "scopes": rows, "text": self.text}


# MARK: The call graph

CALL = re.compile(r"(?<![\w@#.\\$])(?P<q>(?:[A-Za-z_]\w*[?!]?\.)*)(?P<name>[A-Za-z_]\w*)[ \t]*(?P<open>[({])")
DOT = re.compile(r"\.(?P<name>[A-Za-z_]\w*)[ \t]*(?P<open>\()")


class Graph:
    def __init__(self, files):
        self.files = files
        self.scopes = []  # (file index, local index)
        for fi, f in enumerate(files):
            f.first = len(self.scopes)
            self.scopes.extend((fi, k) for k in range(len(f.scopes)))
        self.types, self.extensions, self.members, self.by_name, self.globals = defaultdict(list), defaultdict(list), defaultdict(list), defaultdict(list), defaultdict(list)
        self.enums_with_case = defaultdict(list)
        for g, (fi, k) in enumerate(self.scopes):
            sc = files[fi].scopes[k]
            simple = sc["name"].split(".")[-1]
            if sc["kind"] in TYPES:
                self.types[simple].append(g)
            if sc["kind"] == "X":
                self.extensions[simple].append(g)
            for case in sc["cases"] or []:
                self.enums_with_case[case].append(g)
        for g, (fi, k) in enumerate(self.scopes):
            sc = files[fi].scopes[k]
            if sc["kind"] not in CALLABLE:
                continue
            parent = files[fi].scopes[sc["parent"]] if sc["parent"] >= 0 else None
            if parent and parent["kind"] in TYPES | {"X"}:
                self.members[(parent["name"].split(".")[-1], sc["name"])].append(g)
            if sc["kind"] != "i" and not sc["flags"] & LOCAL:
                self.by_name[sc["name"]].append(g)
            if sc["kind"] == "f" and not parent:
                self.globals[sc["name"]].append(g)
        self.edges, self.unresolved, self.likely_names = {}, Counter(), Counter()

    def scope(self, g):
        fi, k = self.scopes[g]
        return self.files[fi].scopes[k]

    @staticmethod
    def accepts(params, labels, trailing):
        i, j, n = 0, 0, len(params)
        while i < n and j < len(labels):
            label, default, closure, variadic = params[i]
            if labels[j] == label:
                i += 1
                j += 1
                while variadic and j < len(labels) and labels[j] == "_":
                    j += 1
            elif default:
                i += 1
            else:
                return False
        if j < len(labels):
            return False
        if trailing:
            while i < n and not params[i][2]:
                if not params[i][1]:
                    return False
                i += 1
            if i >= n:
                return False
            i += 1
        return all(p[1] for p in params[i:])

    def matching(self, candidates, labels, trailing):
        return [g for g in candidates if self.accepts(self.scope(g)["params"], labels, trailing)]

    def chain(self, fi, offset):
        """The named scopes around an offset, innermost first, as global indices."""
        f = self.files[fi]
        inner = None
        for k, sc in enumerate(f.scopes):
            if sc["brace_off"] is not None and sc["brace_off"] < offset <= sc["end_off"]:
                if inner is None or sc["brace_off"] > f.scopes[inner]["brace_off"]:
                    inner = k
        out = []
        while inner is not None and inner >= 0:
            out.append(f.first + inner)
            inner = f.scopes[inner]["parent"]
        return out

    def type_members(self, simple, name):
        return self.members.get((simple, name), [])

    def construct(self, name, labels, trailing):
        if name not in self.types:
            return []
        inits = [g for t in [name] for g in self.type_members(t, "init")]
        hits = self.matching(inits, labels, trailing)
        if len(hits) == 1:
            return [(hits[0], 0)]
        if len(hits) > 1:
            return [(g, 2) for g in hits[:FANOUT]]
        types = self.types[name]
        return [(types[0], 0)] if len(types) == 1 else [(g, 2) for g in types[:FANOUT]]

    def unqualified(self, chain, name, labels, trailing):
        for a in chain:
            local = [g for g in self.by_name_local(name) if self.scope(g)["parent"] == self.scopes[a][1] and self.scopes[g][0] == self.scopes[a][0]]
            hits = self.matching(local, labels, trailing)
            if len(hits) == 1:
                return [(hits[0], 0)]
        for a in chain:
            sc = self.scope(a)
            if sc["kind"] in TYPES | {"X"}:
                hits = self.matching(self.type_members(sc["name"].split(".")[-1], name), labels, trailing)
                if len(hits) == 1:
                    return [(hits[0], 0)]
                if 1 < len(hits) <= FANOUT:
                    return [(g, 2) for g in hits]
        hits = self.matching(self.globals.get(name, []), labels, trailing)
        if len(hits) == 1:
            return [(hits[0], 0)]
        return [(g, 2) for g in hits] if 1 < len(hits) <= FANOUT else []

    def by_name_local(self, name):
        if not hasattr(self, "_locals"):
            self._locals = defaultdict(list)
            for g in range(len(self.scopes)):
                sc = self.scope(g)
                if sc["kind"] == "f" and sc["flags"] & LOCAL:
                    self._locals[sc["name"]].append(g)
        return self._locals.get(name, [])

    def receiver(self, name, labels, trailing):
        if name in SHADOWED:
            return []
        hits = self.matching(self.by_name.get(name, []), labels, trailing)
        if len(hits) == 1:
            self.likely_names[name] += 1
            return [(hits[0], 1)]
        return [(g, 2) for g in hits] if 1 < len(hits) <= FANOUT else []

    def implicit(self, name, labels, trailing):
        if name in SHADOWED:
            return []
        funcs = [g for g in self.matching(self.by_name.get(name, []), labels, trailing) if "static" in self.scope(g)["mods"]]
        hits = funcs + self.enums_with_case.get(name, [])
        if len(hits) == 1:
            self.likely_names[name] += 1
            return [(hits[0], 1)]
        return [(g, 2) for g in hits] if 1 < len(hits) <= FANOUT else []

    def resolve(self, fi, offset, quals, name, kind, labels, trailing):
        chain = self.chain(fi, offset)
        if kind == "implicit":
            return chain, self.implicit(name, labels, trailing)
        if kind == "chained":
            return chain, self.receiver(name, labels, trailing)
        if not quals:
            if name[0].isupper():
                return chain, self.construct(name, labels, trailing)
            return chain, self.unqualified(chain, name, labels, trailing)
        head, last = quals[0], quals[-1]
        if head == "super":
            return chain, []
        if quals in (["self"], ["Self"]):
            return chain, self.unqualified([a for a in chain if self.scope(a)["kind"] in TYPES | {"X"}], name, labels, trailing)
        if last[0].isupper():
            if last not in self.types and last not in self.extensions:
                return chain, []
            if name[0].isupper():
                return chain, self.construct(name, labels, trailing)
            cands = self.type_members(last, name)
            hits = self.matching(cands, labels, trailing)
            if len(hits) == 1:
                return chain, [(hits[0], 0)]
            if hits:
                return chain, [(g, 2) for g in hits[:FANOUT]]
            enums = [g for g in self.enums_with_case.get(name, []) if self.scope(g)["name"].split(".")[-1] == last]
            if enums:
                return chain, [(enums[0], 0)]
            return chain, [(cands[0], 1)] if len(cands) == 1 else []
        return chain, self.receiver(name, labels, trailing)

    def call_labels(self, f, open_at):
        blank = f.blank
        close = closing_paren(blank, open_at)
        if close is None:
            return [], False, open_at
        inner = blank[open_at + 1:close]
        labels = []
        if f.text[open_at + 1:close].strip():
            for arg in split_top(inner, ","):
                m = re.match(r"\s*([A-Za-z_]\w*)\s*:(?!:)", arg)
                labels.append(m.group(1) if m else "_")
        after = blank[close + 1:close + 40]
        trailing = bool(re.match(r"[ \t]*\{", after))
        return labels, trailing, close

    def sites(self, fi):
        f = self.files[fi]
        blank = f.blank
        heads = sorted((sc["head_off"], sc["brace_off"] if sc["brace_off"] is not None else sc["end_off"]) for sc in f.scopes)
        head_starts = [h[0] for h in heads]

        def in_head(offset):
            k = bisect.bisect_right(head_starts, offset) - 1
            return k >= 0 and heads[k][0] <= offset < heads[k][1]

        def line_info(offset):
            n = f.line_of(offset)
            text = f.blank_line(n)
            m = re.match(r"\s*(?:\}\s*)?([A-Za-z_]\w*)", text)
            first = m.group(1) if m else ""
            colon = None
            if first == "case":
                top = 0
                for k, ch in enumerate(text):
                    if ch in "([{":
                        top += 1
                    elif ch in ")]}":
                        top -= 1
                    elif ch == ":" and top == 0:
                        colon = f.starts[n - 1] + k
                        break
                colon = colon if colon is not None else f.starts[n] if n < len(f.starts) else len(blank)
            return n, first, colon

        named = set()
        for m in CALL.finditer(blank):
            name, off = m.group("name"), m.start("name")
            named.add(off)
            quals = [q.rstrip("?!") for q in m.group("q").split(".") if q]
            if name in KEYWORDS or (quals and quals[0] in ("super",)) or in_head(m.start()):
                continue
            n, first, colon = line_info(off)
            if colon is not None and off < colon:
                continue
            if m.group("open") == "{":
                before = blank[f.starts[n - 1]:m.start()].strip()
                if not (name[0].isupper() or quals) or (before and not re.search(r"(?:[=(,:\[]|\breturn|\btry|\bawait)$", before)):
                    continue
                labels, trailing = [], True
            else:
                labels, trailing, _ = self.call_labels(f, m.start("open"))
                if trailing and first in CONTROL:
                    trailing = False
            yield off, n, quals, name, "call", labels, trailing
        for m in DOT.finditer(blank):
            name, off = m.group("name"), m.start("name")
            if off in named or name in KEYWORDS or in_head(m.start()):
                continue
            n, first, colon = line_info(off)
            if colon is not None and off < colon:
                continue
            k = m.start() - 1
            while k >= 0 and blank[k] in " \t\n":
                k -= 1
            prev = blank[k] if k >= 0 else ""
            kind = "chained" if (prev.isalnum() or prev in ")]?!_$") else "implicit"
            if prev.isdigit():
                continue
            labels, trailing, _ = self.call_labels(f, m.start("open"))
            if trailing and first in CONTROL:
                trailing = False
            yield off, n, [], name, kind, labels, trailing

    def build(self):
        declared = set(self.by_name) | set(self.types) | {"init"}
        for fi in range(len(self.files)):
            for off, line, quals, name, kind, labels, trailing in self.sites(fi):
                chain, targets = self.resolve(fi, off, quals, name, kind, labels, trailing)
                if not chain:
                    continue
                if not targets:
                    if name in declared and name not in SHADOWED:
                        self.unresolved[name] += 1
                    continue
                source = chain[0]
                for target, tier in targets:
                    key = (source, target)
                    if key in self.edges:
                        e = self.edges[key]
                        e[2] = min(e[2], tier)
                        e[4] += 1
                    else:
                        self.edges[key] = [source, target, tier, line, 1]
        return sorted(self.edges.values(), key=lambda e: (e[0], e[3], e[1]))


# MARK: The trail

def slug(heading):
    return re.sub(r"\s+", "-", re.sub(r"[^\w\s-]", "", heading.lower()).strip())


def check_prose(where, text):
    """The rules the site's prose follows, for text the page renders at runtime, where check.py never reads it."""
    for phrase in BANNED:
        if re.search(r"\b" + re.escape(phrase) + r"\b", text.lower()):
            fail(f"{where}: says “{phrase}”")
    if re.search(r"\([^)]*[a-z][^)]*\)", text) and not re.search(r"\b[A-Za-z_]+\([^)]*\)", text):
        fail(f"{where}: a parenthesis inside the text")


def resolve_trails(files, graph, ids, edges):
    """trails.json: four trails, training and inference and the same two for questions, each 3 to 9 steps of
    declarations in the order they run. A declaration is on a trail at most once, and may be on several, with a
    note for each. A trail's mark, one or two capitals, is its badge in the tree: T3 is step 3 of training."""
    spec = json.loads(TRAILS.read_text(encoding="utf-8"))
    anchors = {slug(m.group(1)) for m in re.finditer(r"^## (.+)$", ARCHITECTURE.read_text(encoding="utf-8"), re.M)}
    linked = {(e[0], e[1]) for e in edges}
    trails, warnings = [], []
    if [t.get("id") for t in spec.get("trails", [])] != ["training", "inference", "qa-training", "qa-inference"]:
        fail("trails.json must hold four trails: training, inference, qa-training, qa-inference")
    marks = [t.get("mark", "") for t in spec["trails"]]
    if len(set(marks)) != len(marks) or not all(re.fullmatch(r"[A-Z]{1,2}", m) for m in marks):
        fail("every trail needs its own mark of one or two capitals: " + ", ".join(marks))
    for trail in spec["trails"]:
        tid = trail["id"]
        for key in ("title", "subtitle", "say"):
            if not trail.get(key):
                fail(f"trail {tid}: no {key}")
            check_prose(f"trail {tid}: its {key}", trail[key])
        steps, order, seen = [], [], {}
        for step in trail["steps"]:
            entries = []
            for entry in step["entries"]:
                want = entry["scope"]
                file_part, _, scope_part = want.rpartition(":") if re.match(r"^[\w/]+\.swift:", want) else ("", "", want)
                labelled = "(" in scope_part
                found = []
                for g, (fi, k) in enumerate(graph.scopes):
                    f = files[fi]
                    if file_part and not f.path.endswith("/" + file_part) and Path(f.path).name != file_part:
                        continue
                    tail = ids[g].split(":", 1)[1]
                    if labelled and tail.split("~")[0] == scope_part:
                        found.append(g)
                    elif not labelled and f.qualified(k) == scope_part:
                        found.append(g)
                where = f"{tid} trail, step {step['n']}: {want}"
                if len(found) != 1:
                    fail(f"{where} matches {len(found)} scopes" + ("; add the labels or the file: " + ", ".join(ids[g] for g in found) if found else ""))
                g = found[0]
                if g in seen:
                    fail(f"{where} is already on the {tid} trail at step {seen[g]}; a declaration is on a trail once")
                seen[g] = step["n"]
                fi, k = graph.scopes[g]
                f, sc = files[fi], files[fi].scopes[k]
                body = "\n".join(f.lines[sc["decl"] - 1:sc["end"]])
                if entry.get("anchor") and entry["anchor"] not in body:
                    fail(f"{where}: {ids[g]} no longer holds {entry['anchor']!r}; re-check the entry")
                note = entry.get("note", "")
                check_prose(where + "'s note", note)
                cite = entry.get("cite", "")
                if cite.startswith("ARCHITECTURE.md#"):
                    if cite.split("#", 1)[1] not in anchors:
                        fail(f"{where}: ARCHITECTURE.md has no heading #{cite.split('#', 1)[1]}")
                elif cite == "PIN":
                    if not (f.header and f.header["pin"]):
                        fail(f"{where}: cites the PIN of {f.path}, which has none")
                elif cite not in ("", "WHAT"):
                    fail(f"{where}: the cite must be ARCHITECTURE.md#<heading>, PIN or WHAT")
                entries.append({"scope": g, "id": ids[g], "note": note, "cite": cite})
                order.append((g, entry.get("link") == "none", where))
            steps.append({"n": step["n"], "title": step["title"], "chapters": step["chapters"], "entries": entries})
        if [s_["n"] for s_ in steps] != list(range(1, len(steps) + 1)) or not 3 <= len(steps) <= 9:
            fail(f"the {tid} trail must number its steps 1, 2, 3… in order, 3 to 9 of them")
        for (a_, _, _), (b_, quiet, where) in zip(order, order[1:]):
            if not quiet and (a_, b_) not in linked and (b_, a_) not in linked:
                warnings.append(f"{where}: no call between it and the entry before")
        trails.append({"id": tid, "title": trail["title"], "mark": trail["mark"], "subtitle": trail["subtitle"], "say": trail["say"], "steps": steps})
    return {"trails": trails}, warnings


# MARK: Running

def load(paths=None):
    files = []
    for module in MODULES:
        root = REPO / "Sources" / module
        if not root.is_dir():
            fail(f"Sources/{module} is missing")
        for p in sorted(q for q in root.rglob("*.swift") if not q.name.startswith("._")):
            rel = p.relative_to(REPO).as_posix()
            if paths and rel not in paths:
                continue
            files.append(SwiftFile(p.read_text(encoding="utf-8"), rel, module))
    return files


def build(stats=False):
    files = load()
    graph = Graph(files)
    edges = graph.build()
    ids = []
    for f in files:
        ids.extend(f.ids())
    trails, warnings = resolve_trails(files, graph, ids, edges)
    trail_scopes = {e["scope"] for t in trails["trails"] for s in t["steps"] for e in s["entries"]}
    kinds = Counter(sc["kind"] for f in files for sc in f.scopes)
    counts = {"files": len(files), "lines": sum(len(f.lines) - 1 for f in files), "bytes": sum(len(f.text.encode("utf-8")) for f in files),
              "scopes": len(ids), "funcs": kinds["f"], "inits": kinds["i"], "types": sum(kinds[k] for k in TYPES),
              "edges": {t: sum(1 for e in edges if e[2] == n) for n, t in enumerate(TIERS)}}
    commit = git_head(REPO)
    dirty = git_dirty(REPO, "Sources")
    index = {"commit": (commit + ", with uncommitted edits") if commit and dirty else commit, "dirty": dirty, "modules": MODULES,
             "files": [{"path": f.path, "module": f.module, "first": f.first, "scopes": len(f.scopes), "lines": len(f.lines) - 1,
                        "bytes": len(f.text.encode("utf-8"))} for f in files],
             "counts": counts,
             "sample": [[g, ids[g]] for g in range(len(ids)) if g in trail_scopes or g % 25 == 0],
             "edges": edges, "trails": trails["trails"]}
    outputs = {}
    for module in MODULES:
        value = {"module": module, "files": [f.record(f.first) for f in files if f.module == module]}
        outputs[module] = js_file(None, module, value)
    outputs["index"] = js_file(None, "index", index)
    total = sum(len(t.encode("utf-8")) for t in outputs.values())
    print(f"sources: {counts['files']} files, {counts['lines']:,} lines, {counts['scopes']:,} scopes "
          f"(func {kinds['f']}, init {kinds['i']}, struct {kinds['S']}, class {kinds['C']}, enum {kinds['E']}, extension {kinds['X']}, "
          f"protocol {kinds['P']}, actor {kinds['A']}, subscript {kinds['s']}, deinit {kinds['d']}, computed var {kinds['v']})")
    print(f"  calls: {len(edges):,} edges · exact {counts['edges']['exact']:,} · likely {counts['edges']['likely']:,} · ambiguous {counts['edges']['ambiguous']:,}"
          f" · {sum(graph.unresolved.values()):,} sites unresolved")
    print("  trails: " + " · ".join(f"{t['id']} {len(t['steps'])} steps, {sum(len(s['entries']) for s in t['steps'])} entries" for t in trails["trails"]) +
          f", {len(warnings)} pairs without a call between them")
    for w in warnings:
        print("  warning:", w)
    print(f"  size: {total / 1048576:.2f} MB of {CAP_MB} MB ({(CAP_MB * 1048576 - total) / 1024:.0f} KB to spare)")
    if total > CAP_MB * 1048576:
        fail(f"data/sources would be {total / 1048576:.2f} MB, over its {CAP_MB} MB budget")
    if stats:
        collisions = [i for i in ids if "~" in i]
        print("  id collisions:", ", ".join(collisions) or "none")
        print("  top unresolved:", ", ".join(f"{n} {c}" for n, c in graph.unresolved.most_common(30)))
        print("  top likely:", ", ".join(f"{n} {c}" for n, c in graph.likely_names.most_common(30)))
        undoc = sum(1 for f in files for sc in f.scopes if sc["kind"] == "f" and not sc["doc"])
        print(f"  funcs without a /// comment: {undoc} of {kinds['f']}")
    return outputs


def write(outputs):
    OUT.mkdir(parents=True, exist_ok=True)
    for module, text in outputs.items():
        (OUT / f"{module}.js").write_text(text, encoding="utf-8")
    for stale in OUT.glob("*.js"):
        if stale.stem not in outputs:
            stale.unlink()
    for module, text in outputs.items():
        if module == "index":
            continue
        value = json.loads(text.split("\n")[3].split(" = ", 1)[1][:-1])
        for f in value["files"]:
            if (REPO / f["path"]).read_text(encoding="utf-8") != f["text"]:
                fail(f"{f['path']} did not survive the round trip into data/sources/{module}.js")
    print(f"wrote {len(outputs)} files to Docs/site/data/sources")


