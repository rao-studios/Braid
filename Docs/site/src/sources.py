"""Writes the code explorer's data: every Swift file under Sources/, verbatim, with its scopes and a static call graph.

    python3 -I Docs/site/src/sources.py               # data/sources/<Module>.js and data/sources/index.js
    python3 -I Docs/site/src/sources.py --check-only  # parse, resolve the two trails, print the totals; write nothing
    python3 -I Docs/site/src/sources.py --self-test   # the parser against the hard shapes, inline
    python3 -I Docs/site/src/sources.py --dump Sources/BraidCore/Strand/Cluster.swift
    python3 -I Docs/site/src/sources.py --stats       # unresolved and likely call names, id collisions, trail links

Inputs: Sources/**/*.swift, Docs/site/src/trails.json, the headings of Docs/ARCHITECTURE.md, and git HEAD.

The parser is a lexer (strings, raw strings, interpolation, comments) and a walk over the braces, not a compiler.
Every file's declarations are counted two ways, by the walk and by a plain count of their keywords, and the build
fails when the two disagree. Calls are matched by name and argument labels, and every edge says how sure the match
is: exact, likely or ambiguous. The page shows that label beside every edge.
"""

