def self_test():
    def parse(text):
        return SwiftFile(text, "Sources/Test/T.swift", "Test", header=False)

    def names(f):
        return [(sc["kind"], f.qualified(k), tuple(p[0] for p in sc.get("params", ())) if sc["kind"] in CALLABLE else None) for k, sc in enumerate(f.scopes)]

    def calls(files):
        g = Graph(files)
        edges = g.build()
        out = []
        for e in edges:
            a, b = g.scopes[e[0]], g.scopes[e[1]]
            out.append((files[a[0]].qualified(a[1]), files[b[0]].qualified(b[1]), TIERS[e[2]]))
        return out

    checks = []

    def check(label, cond):
        checks.append((label, bool(cond)))

    f = parse('func show(_ x: Int) {\n    let s = "H \\(before.map { f($0.hknn) + "→" } ?? "")\\(f(x))"\n}\nfunc f(_ x: Int) -> String { "" }\n')
    check("an interpolation holding a closure with braces leaves one scope per func", names(f) == [("f", "show", ("_",)), ("f", "f", ("_",))])
    check("calls inside interpolations are seen", ("show", "f", "exact") in calls([f]))
    f = parse('enum ID {\n    public static let pattern = #"^(braid)-[0-9a-f]{24}$"#\n    static func ok() -> Bool { "a{".isEmpty }\n}\n')
    check("a raw string with {24} and a string with { open nothing", names(f) == [("E", "ID", None), ("f", "ID.ok", ())])
    f = parse("enum Gate {\n    public static func floor(_ openFloor: Double, strands: Int) -> Double { openFloor * 2 / Double(max(2, strands)) }\n}\n")
    sc = f.scopes[1]
    check("a one-line func", sc["decl"] == sc["brace"][0] == sc["end"] == 2 and sc["flags"] & ONE_LINE and [p[0] for p in sc["params"]] == ["_", "strands"])
    f = parse("enum T {\n    /// Trains.\n    @discardableResult\n    public static func train(languageModule: LanguageModule, continuing: Bool,\n"
              "                             shouldStop: () -> Bool = { false }, onEvent: (Int) -> Void = { _ in }) throws -> Int {\n"
              "        func loss(_ model: LanguageModule) -> Int { 0 }\n        return loss(languageModule)\n    }\n}\n")
    sc = f.scopes[1]
    check("a multi-line signature with closure defaults and an attribute line", [p[0] for p in sc["params"]] == ["languageModule", "continuing", "shouldStop", "onEvent"]
          and sc["decl"] == 3 and sc["sig"] == 4 and sc["doc"] == [2, 2] and len(f.scopes) == 3)
    check("a nested local func is local, qualified by its function", f.qualified(2) == "T.train.loss" and f.scopes[2]["flags"] & LOCAL)
    check("a call to the local func is exact", ("T.train", "T.train.loss", "exact") in calls([f]))
    f = parse("struct P {\n    public static func < (lhs: P, rhs: P) -> Bool { true }\n    public static func == (lhs: P, rhs: P) -> Bool { true }\n}\n")
    check("operator funcs", [n[1] for n in names(f)] == ["P", "P.<", "P.=="] and f.scopes[1]["flags"] & OPERATOR)
    f = parse("struct V {\n    var _x = 0\n    public var x: Int {\n        get { _x }\n        set { _x = newValue }\n    }\n}\n")
    check("a computed var with get and set is one scope", names(f) == [("S", "V", None), ("v", "V.x", None)])
    f = parse('enum B {\n    static let text = """\n        func fake() { {\n        """\n    static func real() {}\n}\n')
    check('a """ string holding func and braces adds nothing', names(f) == [("E", "B", None), ("f", "B.real", ())])
    f = parse("public protocol Node: AnyObject {\n    var layout: Int { get }\n    /// Opens.\n    func open(session: String, tokens: [Int32],\n"
              "              k: Int) throws -> [Int]\n    func close(session: String)\n}\nfinal class Local: Node {\n    var layout: Int { 0 }\n"
              "    func open(session: String, tokens: [Int32], k: Int) throws -> [Int] { [] }\n    func close(session: String) {}\n"
              "    func use(_ n: Node) { _ = try? n.open(session: \"\", tokens: [], k: 1) }\n}\n")
    req = [sc for sc in f.scopes if sc["requirement"]]
    check("protocol requirements without braces", [(sc["kind"], sc["name"]) for sc in req] == [("v", "layout"), ("f", "open"), ("f", "close")]
          and req[1]["doc"] == [3, 3] and req[1]["end"] == 5)
    check("a call through a protocol value is ambiguous between the requirement and the implementation",
          {(a, b, t) for a, b, t in calls([f]) if a == "Local.use"} == {("Local.use", "Node.open", "ambiguous"), ("Local.use", "Local.open", "ambiguous")})
    f = parse("func f(_ xs: [Int], m: Int?) {\n    guard let y = xs.first else { return }\n    if let m = m { print(m) }\n    Task { print(y) }\n"
              "    _ = xs.map { t in t + 1 }\n    let z: [Int] = { [1] }()\n    lazy var w: Int = { 3 }()\n    for t in xs { print(t) }\n}\n")
    check("blocks and closures are not scopes", names(f) == [("f", "f", ("_", "m"))])
    f = parse("enum Event {\n    case attached(name: String, position: Int), detached(name: String)\n    indirect case nested(Event)\n"
              "    func go(_ s: Int) {}\n    func run(_ e: Event) {\n        switch e {\n        case .attached(let s, _): go(s)\n        default: break\n        }\n    }\n}\n")
    check("enum cases are recorded on the enum", f.scopes[0]["cases"] == ["attached", "detached", "nested"])
    edges = calls([f])
    check("a switch pattern makes no edge, the call after its colon does", ("Event.run", "Event.go", "exact") in edges and not any(b == "Event" for _, b, _ in edges))
    f = parse("struct GateState {}\nextension GateState {\n    public init(memoryOnly memory: [Double], commons: Int?) {}\n}\n")
    check("an init in an extension is qualified by the extended type", f.ids()[2] == "Test/T.swift:GateState.init(memoryOnly:commons:)" and f.ids()[1] == "Test/T.swift:extension:GateState")
    check("a header without WHAT fails", raises(lambda: SwiftFile("//\n//  T.swift\n//  Test\n//\n//  PIN: x\n//\n\nimport Foundation\n", "Sources/Test/T.swift", "Test")))
    h = SwiftFile("//\n//  T.swift\n//  Test\n//\n//  WHAT: One\n//        two.\n//  PIN:  Three\n//\n\nimport Foundation\n", "Sources/Test/T.swift", "Test").header
    check("a header's WHAT and PIN ranges", h == {"lines": [1, 8], "what": [5, 6], "pin": [7, 7], "in": None, "out": None})
    f = parse("final class Pool {\n    public class func make() -> Pool { Pool() }\n    class var shared: Int { 1 }\n}\n")
    check("class func and class var are members, not classes", names(f) == [("C", "Pool", None), ("f", "Pool.make", ()), ("v", "Pool.shared", None)])
    f = parse("func f(map: Dictionary<String, Int>, pairs: [String: (Int, Int)], last: Int = 0) {}\n")
    check("commas inside generic and tuple types leave the labels alone", [p[0] for p in f.scopes[0]["params"]] == ["map", "pairs", "last"] and f.scopes[0]["params"][2][1])
    f = parse("struct SessionWriter {\n    func append(_ s: Int) {}\n    func go(items: [Int]) {\n        var items = items\n        items.append(1)\n        self.append(2)\n    }\n}\n")
    edges = calls([f])
    check("a library name through a value makes no edge; through self it is exact", edges == [("SessionWriter.go", "SessionWriter.append", "exact")])
    f = parse("enum Mixer {\n    static func shares(_ w: [Double], token: Int) -> [Double] { [] }\n}\nenum Cluster {\n    static func record() { _ = Mixer.shares([], token: 1)\n"
              "        _ = Recipe(\"x\")\n        _ = Recipe { 1 }\n    }\n}\nstruct Recipe {\n    init(_ name: String) {}\n    init(_ build: () -> Int) {}\n}\n")
    edges = calls([f])
    check("a type-qualified static call is exact", ("Cluster.record", "Mixer.shares", "exact") in edges)
    check("constructors resolve by labels, a trailing closure included", ("Cluster.record", "Recipe.init", "exact") in edges and sum(1 for e in edges if e[1] == "Recipe.init") == 2)
    width = max(len(label) for label, _ in checks)
    for label, ok in checks:
        print(("ok    " if ok else "FAIL  ") + label.ljust(width))
    failed = sum(1 for _, ok in checks if not ok)
    print(f"self-test: {len(checks) - failed} of {len(checks)} passed")
    return failed == 0


def raises(fn):
    try:
        fn()
    except Failure:
        return True
    return False


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check-only", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--dump")
    parser.add_argument("--stats", action="store_true")
    args = parser.parse_args()
    try:
        if args.self_test:
            sys.exit(0 if self_test() else 1)
        if args.dump:
            dump(args.dump)
            return
        outputs = build(stats=args.stats)
        if not args.check_only and not args.stats:
            write(outputs)
    except Failure as e:
        print(f"sources: {e}")
        sys.exit(1)


if __name__ == "__main__":
    main()
